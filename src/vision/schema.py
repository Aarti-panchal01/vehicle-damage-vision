"""Pydantic models for the vision module.

VisionOutput is what the VLM must return. DamageReport is Contract A, the
handoff to Roles 2, 3 and 4. VisionError is returned instead of a report when
the model output cannot be turned into a valid VisionOutput.
"""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from src.vision.vocab import DAMAGE_TYPES, PARTS, QUALITY_ISSUES, SEVERITIES

PartName = Literal[PARTS]
DamageTypeName = Literal[DAMAGE_TYPES]
SeverityName = Literal[SEVERITIES]

QUALITY_FLAG_PATTERN = re.compile(r"^image_(\d+)_(" + "|".join(QUALITY_ISSUES) + r")$")
CLAIM_ID_PATTERN = r"^CLM-\d{8}-\d{3}$"


class Damage(BaseModel):
    """One damaged part as seen in one photo."""

    model_config = ConfigDict(extra="ignore")

    part: PartName
    damage_type: DamageTypeName
    severity: SeverityName
    confidence: float = Field(ge=0.0, le=1.0)
    image_index: int = Field(ge=0)
    notes: str = ""


class VisionOutput(BaseModel):
    """The JSON object the VLM is asked to produce for one request."""

    model_config = ConfigDict(extra="ignore")

    damages: list[Damage]
    image_quality_flags: list[str] = Field(default_factory=list)

    @field_validator("image_quality_flags")
    @classmethod
    def check_quality_flags(cls, flags: list[str]) -> list[str]:
        """Reject flags that do not follow image_<index>_<issue>."""
        bad = [flag for flag in flags if not QUALITY_FLAG_PATTERN.match(flag)]
        if bad:
            raise ValueError(
                f"invalid image_quality_flags {bad}; each flag must look like image_<index>_<issue> "
                f"with issue one of {list(QUALITY_ISSUES)}"
            )
        return flags


class Vehicle(BaseModel):
    """Vehicle details typed by the user in the form, never filled by the VLM."""

    make: str
    model: str
    year: int = Field(ge=1980, le=2100)
    fuel: str


class DamageReport(BaseModel):
    """Contract A: the damage report handed to the cost engine, RAG and UI."""

    claim_id: str = Field(pattern=CLAIM_ID_PATTERN)
    vehicle: Vehicle
    user_description: str
    damages: list[Damage]
    image_quality_flags: list[str]
    model_used: str
    prompt_strategy: str


class VisionError(BaseModel):
    """Structured failure returned when no valid damage report could be produced."""

    claim_id: str
    error_code: Literal["invalid_model_output", "provider_error", "quota_exhausted", "bad_input"]
    message: str
    attempts: int
    last_raw_output: str | None = None
    model_used: str
    prompt_strategy: str


def vision_output_json_schema(include_analysis: bool = False) -> dict:
    """Return a strict JSON Schema for VisionOutput usable by Gemini and Groq structured output.

    Written by hand instead of exported from Pydantic so it has no $ref and
    satisfies Groq strict mode (every property required, no extra keys).
    """
    damage_schema = {
        "type": "object",
        "properties": {
            "part": {"type": "string", "enum": list(PARTS)},
            "damage_type": {"type": "string", "enum": list(DAMAGE_TYPES)},
            "severity": {"type": "string", "enum": list(SEVERITIES)},
            "confidence": {"type": "number"},
            "image_index": {"type": "integer"},
            "notes": {"type": "string"},
        },
        "required": ["part", "damage_type", "severity", "confidence", "image_index", "notes"],
        "additionalProperties": False,
    }
    properties: dict = {}
    if include_analysis:
        properties["analysis"] = {"type": "string"}
    properties["damages"] = {"type": "array", "items": damage_schema}
    properties["image_quality_flags"] = {"type": "array", "items": {"type": "string"}}
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def contract_a_json_schema() -> dict:
    """Return the JSON Schema of Contract A as generated by Pydantic."""
    schema = DamageReport.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["title"] = "Contract A: Damage report"
    return schema
